/** "Fit in fewer parts": replace characters that force Unicode (UCS-2) with GSM-7 lookalikes. */
const MAP: Record<string, string> = {
  "‘": "'", "’": "'", "‚": "'", "‛": "'", "“": '"', "”": '"', "„": '"', "‟": '"', "«": '"', "»": '"',
  "–": "-", "—": "-", "―": "-", "‐": "-", "‑": "-", "−": "-", "…": "...", "•": "-", "·": ".",
  "→": "->", "←": "<-", "⇒": "=>", "×": "x", "÷": "/", "™": "TM", "©": "(c)", "®": "(R)",
  " ": " ", " ": " ", "​": "", " ": " ", " ": " ",
  "á": "a", "â": "a", "ã": "a", "ā": "a", "ă": "a", "ą": "a", "ç": "c", "ć": "c", "č": "c", "ď": "d", "đ": "d",
  "ê": "e", "ë": "e", "ē": "e", "ę": "e", "ě": "e", "ğ": "g", "í": "i", "î": "i", "ï": "i", "ī": "i", "ı": "i",
  "ł": "l", "ń": "n", "ň": "n", "ó": "o", "ô": "o", "õ": "o", "ō": "o", "ő": "o", "ř": "r", "ś": "s", "ş": "s", "š": "s", "ș": "s",
  "ť": "t", "ț": "t", "ú": "u", "û": "u", "ū": "u", "ů": "u", "ű": "u", "ý": "y", "ÿ": "y", "ź": "z", "ż": "z", "ž": "z",
  "Á": "A", "Â": "A", "Ã": "A", "Ā": "A", "Ć": "C", "Č": "C", "Ê": "E", "Ë": "E", "Í": "I", "Î": "I", "Ó": "O", "Ô": "O", "Õ": "O",
  "Ś": "S", "Š": "S", "Ş": "S", "Ú": "U", "Û": "U", "Ý": "Y", "Ž": "Z", "Ż": "Z", "Ł": "L", "Ğ": "G", "İ": "I",
};

export function toGsmFriendly(text: string) {
  let out = "";
  for (const ch of text) out += MAP[ch] ?? ch;
  return out;
}
